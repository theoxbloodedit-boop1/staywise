import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';
import { PUBLIC_SEO_META, type SeoRouteMeta } from '../src/seo/Seo.js';
import { DEFAULT_OG_IMAGE, SITE_ORIGIN } from '../src/seo/schema.js';

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function buildHeadTags(spec: SeoRouteMeta): string {
  const canonicalUrl = `${SITE_ORIGIN}${spec.path === '/' ? '/' : spec.path}`;
  const lines: string[] = [];
  if (spec.noindex) {
    lines.push('<meta name="robots" content="noindex, nofollow, noarchive" />');
  } else {
    lines.push(`<link rel="canonical" href="${escapeHtml(canonicalUrl)}" />`);
    lines.push('<meta name="robots" content="index, follow" />');
  }
  lines.push('<meta property="og:site_name" content="Staywise" />');
  lines.push('<meta property="og:type" content="website" />');
  lines.push(`<meta property="og:title" content="${escapeHtml(spec.title)}" />`);
  lines.push(`<meta property="og:description" content="${escapeHtml(spec.description)}" />`);
  lines.push(`<meta property="og:url" content="${escapeHtml(canonicalUrl)}" />`);
  lines.push(`<meta property="og:image" content="${escapeHtml(DEFAULT_OG_IMAGE)}" />`);
  lines.push('<meta name="twitter:card" content="summary_large_image" />');
  lines.push(`<meta name="twitter:title" content="${escapeHtml(spec.title)}" />`);
  lines.push(`<meta name="twitter:description" content="${escapeHtml(spec.description)}" />`);
  lines.push(`<meta name="twitter:image" content="${escapeHtml(DEFAULT_OG_IMAGE)}" />`);

  if (spec.schemas?.length) {
    for (const block of spec.schemas) {
      lines.push(`<script type="application/ld+json">${JSON.stringify(block)}</script>`);
    }
  }
  return lines.map((l) => `    ${l}`).join('\n');
}

function injectIntoTemplate(templateHtml: string, spec: SeoRouteMeta, renderedReactHtml: string): string {
  let out = templateHtml;
  out = out.replace(/<title>[\s\S]*?<\/title>/i, `<title>${escapeHtml(spec.title)}</title>`);
  out = out.replace(
    /<meta\s+name="description"[\s\S]*?\/>/i,
    `<meta name="description" content="${escapeHtml(spec.description)}" />`
  );
  out = out.replace('</head>', `${buildHeadTags(spec)}\n  </head>`);
  const ssrAttr = !spec.is404 && spec.path !== '/auth' ? ` data-ssr-route="${escapeHtml(spec.path)}"` : '';
  out = out.replace('<div id="root"></div>', `<div id="root"${ssrAttr}>${renderedReactHtml}</div>`);
  return out;
}

async function main() {
  const distDir = path.resolve(process.cwd(), 'dist');
  const basePath = path.join(distDir, 'index.html');
  const ssrEntryPath = path.resolve(process.cwd(), '.ssr-tmp', 'entry-server.js');
  if (!fs.existsSync(basePath)) {
    throw new Error('dist/index.html missing — run vite build before prerender.');
  }
  if (!fs.existsSync(ssrEntryPath)) {
    throw new Error('.ssr-tmp/entry-server.js missing — run vite build --ssr src/entry-server.tsx --outDir .ssr-tmp first.');
  }

  const baseTemplate = fs.readFileSync(basePath, 'utf-8');
  const ssrMod = await import(pathToFileURL(ssrEntryPath).href);
  const renderRouteHtml: (p: string) => string = ssrMod.renderRouteHtml;

  let notFoundHtml = '';
  const routeHtml: Record<string, string> = {};

  for (const spec of Object.values(PUBLIC_SEO_META)) {
    const reactHtml = renderRouteHtml(spec.path);
    const fullHtml = injectIntoTemplate(baseTemplate, spec, reactHtml);
    if (spec.is404) {
      notFoundHtml = fullHtml;
      continue;
    }
    fs.writeFileSync(path.join(distDir, spec.file), fullHtml, 'utf-8');
    routeHtml[spec.path] = fullHtml;
  }

  const appShellHtml = baseTemplate.replace(
    '</head>',
    '    <meta name="robots" content="noindex, nofollow, noarchive" />\n  </head>'
  );
  const generatedTs = `/* AUTO-GENERATED by scripts/prerender.ts — do not edit manually */
export const APP_SHELL_HTML = ${JSON.stringify(appShellHtml)};
export const NOT_FOUND_HTML = ${JSON.stringify(notFoundHtml)};
export const ROUTE_HTML: Record<string, string> = ${JSON.stringify(routeHtml)};
`;
  fs.writeFileSync(path.resolve(process.cwd(), 'server', 'generated-shell.ts'), generatedTs, 'utf-8');
  console.log(`SSR prerendered ${Object.keys(routeHtml).length} static HTML routes + 404 + server/generated-shell.ts`);
}

main().catch((err) => {
  console.error('Prerender failed:', err);
  process.exit(1);
});
